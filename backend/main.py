@app.get("/ports/{code}/reality")
def port_reality(
    code: str,
    vessel_dwt: float,
    draft_m: float,
    loa_m: float,
    beam_m: float,
    vessel_class: str | None = None,
    vessel_is_laden: bool | None = None,
    commodity: str = "Dry Bulk",
    as_of: date | None = None,
) -> dict[str, Any]:
    """P2: the M4 Berth Reality Engine's three-state verdict (FEASIBLE /
    INFEASIBLE / CANNOT_VERIFY) for one vessel at one port -- geometry,
    draft, tide authority, empirical wait/handling, observed-vs-declared
    conflicts, all in one real, sourced, dated report."""
    port = _resolve_port(code, "code")
    resolved_as_of = as_of if as_of is not None else latest_available_date()
    report = _cached_port_reality(
        port, draft_m, loa_m, beam_m, vessel_dwt, vessel_class, vessel_is_laden, commodity, resolved_as_of,
    )
    return model_to_json(report)


@app.get("/ports/{code}/berths")
def port_berths(code: str) -> dict[str, Any]:
    """Register rows for this port, with provenance and effective dates --
    an explicit NOT_AVAILABLE payload (never an empty 200 masquerading as
    'no berths exist') for a port with no register entry."""
    port = _resolve_port(code, "code")
    register_port_id: PortId | None = _REGISTER_PORT_ID.get(port)
    if register_port_id is None:
        return {
            "port": port.name, "status": "NOT_AVAILABLE",
            "reason": f"{port.name} has no berth_truth constraint register entry.",
            "berths": [],
        }
    rows = rows_for_port(register_port_id)
    return {"port": port.name, "status": "OK", "berths": [model_to_json(r) for r in rows]}


@app.get("/ports/{code}/calls")
def port_calls(
    code: str, date_from: date | None = None, date_to: date | None = None,
    limit: int = 50, offset: int = 0,
) -> dict[str, Any]:
    """Paginated real fact_port_call rows for this port. NOT_AVAILABLE (not
    an empty 200) when this session's store has genuinely never ingested
    anything for the port, distinguished from a real, empty date-range
    query."""
    port = _resolve_port(code, "code")
    if limit <= 0 or limit > 500:
        raise HTTPException(status_code=422, detail="limit must be between 1 and 500.")
    store = FactPortCallStore()
    all_rows = store.query(port=port, date_from=date_from, date_to=date_to)
    if not all_rows and not store.query(port=port):
        return {"port": port.name, "status": "NOT_AVAILABLE", "total": 0, "rows": []}
    page = all_rows[offset : offset + limit]
    return {
        "port": port.name, "status": "OK", "total": len(all_rows),
        "rows": [model_to_json(r) for r in page],
    }


@app.get("/ports/{code}/waits")
def port_waits(
    code: str, vessel_class: str | None = None, commodity: str | None = None,
) -> dict[str, Any]:
    """Empirical wait distribution (all four real intervals) for this port,
    or an explicit BASELINE_ONLY status when the real sample is too thin --
    never a fabricated percentile."""
    port = _resolve_port(code, "code")
    distributions = {
        interval.value: model_to_json(
            compute_wait_distribution(port, interval, vessel_class=vessel_class, commodity_class=commodity)
        )
        for interval in WaitInterval
    }
    any_sufficient = any(d["is_sufficient"] for d in distributions.values())
    portwatch_status, portwatch_note = PORTWATCH_MAPPING_STATUS.get(port, (None, ""))
    return {
        "port": port.name,
        "status": "OK" if any_sufficient else "BASELINE_ONLY",
        "distributions": distributions,
        "portwatch_mapping_status": portwatch_status.value if portwatch_status else None,
        "portwatch_mapping_note": portwatch_note or None,
    }


