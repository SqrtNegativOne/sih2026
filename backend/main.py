def _latest_on_or_before(df: pl.DataFrame, as_of: date, group_cols: list[str]) -> pl.DataFrame:
    """The latest row per group with date <= as_of -- an as-of read, matching
    the join_asof(strategy="backward") semantics used throughout tonnage/."""
    return df.filter(pl.col("date") <= as_of).sort("date").group_by(group_cols, maintain_order=False).last()


