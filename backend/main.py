def _sse(event: str, data: object) -> str:
    return f"event: {event}\ndata: {json.dumps(data)}\n\n"


@app.post("/quote/stream")
async def post_quote_stream(req: QuoteRequest) -> StreamingResponse:
    """Same result as ``POST /quote``, but streamed as Server-Sent Events: one
    ``stage`` event per pipeline step as it starts and finishes, then a single
    ``result`` event carrying the envelope (or an ``error`` event)."""
    loop = asyncio.get_running_loop()
    queue: asyncio.Queue[tuple[str, object] | None] = asyncio.Queue()

    def on_progress(stage: ProgressStage) -> None:
        loop.call_soon_threadsafe(queue.put_nowait, ("stage", stage.model_dump(mode="json")))

    async def worker() -> None:
        try:
            payload = await run_in_threadpool(_run_quote_envelope, req, on_progress)
            loop.call_soon_threadsafe(queue.put_nowait, ("result", payload))
        except HTTPException as exc:
            loop.call_soon_threadsafe(
                queue.put_nowait, ("error", {"status_code": exc.status_code, "detail": exc.detail})
            )
        except Exception as exc:  # noqa: BLE001 -- surface anything else to the client too
            loop.call_soon_threadsafe(
                queue.put_nowait, ("error", {"status_code": 500, "detail": str(exc)})
            )
        finally:
            loop.call_soon_threadsafe(queue.put_nowait, None)

    async def gen() -> AsyncIterator[str]:
        task = asyncio.create_task(worker())
        try:
            while True:
                item = await queue.get()
                if item is None:
                    break
                event, data = item
                yield _sse(event, data)
        finally:
            await task

    return StreamingResponse(gen(), media_type="text/event-stream")


