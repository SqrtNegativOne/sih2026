def _quote_partial_landed_cost(quote: Any) -> dict[str, Any] | None:
    """P6: auto-computed, assumption-free slice of opt.landed_cost for
    POST /quote's response -- freight, from the quote's own real forecast
    and transit-day estimate. `None` when opt.present couldn't get a real
    transit-day estimate for this route (the same condition that makes
    ``QuoteResult.today_quote_usd_per_mt`` itself ``None``) -- there is then
    nothing real to convert $/day into $/MT with.

    Wait cost is deliberately NOT computed here even though
    opt.landed_cost.compute_landed_cost would happily return a number:
    QuoteRequest carries no per-vessel opex_usd_per_day, and passing 0.0
    would silently zero out a real, sufficient empirical wait estimate --
    reading as "we checked, it's negligible" instead of the true "we don't
    know your opex." Handling/demurrage/commodity/FX need commercial terms
    QuoteRequest doesn't carry either. See POST /landed-cost for the full,
    assumption-informed breakdown."""
    if quote.assumed_transit_days is None:
        return None
    breakdown = compute_landed_cost(LandedCostRequest(
        dest_port=quote.dest_port, cargo_volume_mt=quote.cargo_volume_dwt,
        freight_usd_per_day=quote.today_quote_usd_per_day, voyage_days=quote.assumed_transit_days,
        vessel_class=quote.target_vessel_class, commodity_class=quote.commodity, as_of=quote.as_of,
    ))
    from dataclasses import replace

    real_wait_cost = breakdown.wait_cost_usd_per_mt or 0.0
    missing = [c for c in breakdown.components_missing]
    if "wait_cost" not in missing:
        missing.append("wait_cost")
    honest = replace(
        breakdown,
        wait_cost_usd_per_mt=None, wait_cost_provenance=None,
        wait_cost_reason="opex_usd_per_day is not available at the /quote level -- see POST /landed-cost.",
        components_included=tuple(c for c in breakdown.components_included if c != "wait_cost"),
        components_missing=tuple(missing),
        partial_total_usd_per_mt=breakdown.partial_total_usd_per_mt - real_wait_cost,
        partial_total_inr_per_mt=(
            (breakdown.partial_total_usd_per_mt - real_wait_cost) * breakdown.fx_inr_per_usd
            if breakdown.fx_inr_per_usd is not None else None
        ),
    )
    return _landed_cost_to_json(honest)


def _run_quote_envelope(req: QuoteRequest, on_progress=None) -> dict[str, Any]:
    """Shared body for ``POST /quote`` and ``POST /quote/stream``: resolve the
    request, run ``quote_envelope``, JSON-shape it. Raises HTTPException for a
    malformed request or missing real data, exactly as before."""
    origin = _resolve_port(req.origin_port, "origin_port")
    dest = _resolve_port(req.dest_port, "dest_port")
    if req.laycan_end < req.laycan_start:
        raise HTTPException(
            status_code=422,
            detail=f"laycan_end ({req.laycan_end}) is before laycan_start ({req.laycan_start}).",
        )
    vessels = _resolve_vessels(req.vessels)
    try:
        envelope = quote_envelope(
            cargo_volume_dwt=req.cargo_volume_dwt,
            origin_port=origin,
            dest_port=dest,
            laycan_start=req.laycan_start,
            laycan_end=req.laycan_end,
            contract_term_days=req.contract_term_days,
            commodity=req.commodity,
            as_of=req.as_of,
            risk_tolerance=req.risk_tolerance,
            vessels=vessels,
            revenue_usd=req.revenue_usd,
            on_progress=on_progress,
        )
    except InsufficientMarketDataError as exc:
        raise HTTPException(status_code=503, detail=str(exc)) from exc
    except ValueError as exc:
        raise HTTPException(status_code=422, detail=str(exc)) from exc

    # P5 requirement 6: "on each recommendation store" -- every real, priced
    # quote this endpoint returns (feasible or contingent_infeasible; a
    # structural_infeasible envelope has no .quote to record) becomes a real
    # Live Decision Ledger entry. exercise_boundary is not recorded here:
    # QuoteResult does not currently expose opt.stopping's StoppingResult
    # (see opt.ledger.record_recommendation's own docstring) -- a disclosed
    # gap, not silently worked around.
    if envelope.quote is not None:
        ledger.record_recommendation(envelope.quote, risk_tolerance=req.risk_tolerance)

    payload = quote_envelope_to_json(envelope)
    # P6: additive -- a real, assumption-free partial landed-cost slice
    # (freight only; see _quote_partial_landed_cost) alongside the existing
    # envelope, never replacing anything it already returns.
    if envelope.quote is not None:
        payload["landed_cost"] = _quote_partial_landed_cost(envelope.quote)
    return payload


