def _resolve_port(name: str, field: str) -> PortEnum:
    try:
        return PortEnum[name.strip().upper()]
    except KeyError:
        valid = ", ".join(p.name for p in PortEnum)
        raise HTTPException(
            status_code=422, detail=f"Unknown {field} {name!r}. Valid ports: {valid}"
        ) from None


def _resolve_vessel_class(name: str, field: str) -> VesselClass:
    candidate = name.strip()
    for value in (candidate, candidate.capitalize()):
        try:
            return VesselClass(value)
        except ValueError:
            continue
    valid = ", ".join(c.value for c in VesselClass)
    raise HTTPException(status_code=422, detail=f"Unknown {field} {name!r}. Valid classes: {valid}")


