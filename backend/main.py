def _attach_to_uvicorn_logging() -> None:
    """Make this module's and the harvester's INFO lines actually appear.

    Uvicorn installs its own handlers and does not touch the root logger, so a
    plain ``LOGGER.info`` from here goes to a logger with no handler and is
    dropped at WARNING by logging's last resort. The effect was that the daily
    rate refresh ran, fetched, wrote seven days of new data and fired an alert
    -- and the server log said nothing at all about any of it.

    A background job whose activity is invisible is one nobody can trust or
    debug, so these three loggers borrow uvicorn's handler when there is one
    and fall back to a basic handler when the app is run some other way.
    """
    uvicorn_error = logging.getLogger("uvicorn.error")
    handlers = uvicorn_error.handlers or logging.getLogger().handlers
    for name in (__name__, "data_builders.harvest_handybulk", "alerts"):
        target = logging.getLogger(name)
        target.setLevel(logging.INFO)
        if not target.handlers and not handlers:
            target.addHandler(logging.StreamHandler())
        for handler in handlers:
            if handler not in target.handlers:
                target.addHandler(handler)
        target.propagate = False



# ---------------------------------------------------------------------------
# Standing alerts: the background evaluation loop
# ---------------------------------------------------------------------------
#
# How often this runs, and why the number is what it is: the market data these
# watches read only changes when a build-time harvester under
# src/data_builders/ is run, which is a manual act. So a tight loop would spend
# almost all of its evaluations re-reading a file that has not changed. What
# does move on its own is the clock, and one watch kind (OUTCOME_OVERDUE)
# depends on it -- a ledger entry becomes overdue with no new data at all.
#
# Fifteen minutes is chosen for that: fast enough that a clock-based condition
# is noticed the same working hour, slow enough that the parquet read is
# negligible. It is not a live market feed and the UI does not claim to be one.
ALERT_INTERVAL_SECONDS: Final[float] = float(
    os.environ.get("DESK_ALERT_INTERVAL_SECONDS", "900")
)

#: Set to disable the loop entirely (tests, or a deployment that would rather
#: drive evaluation from cron against POST /alerts/evaluate).
ALERTS_DISABLED: Final[bool] = os.environ.get("DESK_DISABLE_ALERT_LOOP", "").lower() in {
    "1",
    "true",
    "yes",
}

_alert_store: Final[AlertStore] = AlertStore()


async def _alert_loop() -> None:
    """Evaluate every active watch on an interval, forever.

    Each pass runs in a worker thread: the evaluator reads a parquet file and
    the ledger from disk, and doing that on the event loop would stall every
    in-flight request for the duration.

    An exception in one pass is logged and the loop continues. A background
    task that dies silently on the first bad day is worse than no background
    task, because the bell keeps showing a stale count and nothing says why.
    """
    while True:
        try:
            fired = await run_in_threadpool(run_due_watches, _alert_store)
            if fired:
                LOGGER.info("Alert evaluation fired %d watch(es)", len(fired))
        except asyncio.CancelledError:
            raise
        except Exception:
            LOGGER.exception("Alert evaluation pass failed; the loop continues")
        await asyncio.sleep(ALERT_INTERVAL_SECONDS)


# ---------------------------------------------------------------------------
# Keeping the market data current
# ---------------------------------------------------------------------------
#
# The rate series every forecast, ceiling and alert depends on used to advance
# only when somebody ran a scraper by hand -- and nobody had, so the stored
# data sat twelve days behind the source while every downstream figure quietly
# aged. Standing alerts were the sharpest symptom: they watch a number that
# could not change, so they could never fire.
#
# `data_builders.harvest_handybulk` is the harvester that was missing. This
# runs it on a schedule.
#
# On the repository's network policy: that policy forbids a per-request
# external call from backend/ or opt/, and this is not one. It is the
# build-time harvester, in data_builders/, writing to raw_data/, invoked on a
# timer rather than by a request. No HTTP handler waits on it, and a fetch
# failure leaves the existing data exactly as it was.

#: A daily cadence, because the source publishes once a day. Anything faster
#: is asking a question whose answer cannot have changed.
RATE_REFRESH_SECONDS: Final[float] = float(
    os.environ.get("DESK_RATE_REFRESH_SECONDS", str(24 * 60 * 60))
)

#: Set to stop the desk fetching anything at all. A deployment that would
#: rather run the harvester from cron should set this.
RATE_REFRESH_DISABLED: Final[bool] = os.environ.get(
    "DESK_DISABLE_RATE_REFRESH", ""
).lower() in {"1", "true", "yes"}

#: Port-call refresh, disable-able separately from rates because it is a
#: different source with a very different cost: one small query per port,
#: 128 of them, paced at the 400ms the original harvest established as safe.
#: Roughly a minute per pass, once a day.
PORT_REFRESH_DISABLED: Final[bool] = os.environ.get(
    "DESK_DISABLE_PORT_REFRESH", ""
).lower() in {"1", "true", "yes"}


def _refresh_rates_once() -> int:
    """Harvest, fold into master_long, and return how many rows were added.

    Synchronous and blocking by design -- the caller runs it in a worker
    thread. It makes a network request and rewrites a parquet file, neither of
    which belongs on the event loop.
    """
    from data_builders import harvest_handybulk, harvest_route_rates

    result = harvest_handybulk.harvest()
    if not result.fetched:
        LOGGER.info("Rate refresh: %s", result.reason)
        return 0
    if result.conflicts:
        # The source disagreeing with stored history is worth a human looking,
        # and is never applied automatically -- see harvest_handybulk.merge_rows.
        LOGGER.warning(
            "Rate refresh: %d stored value(s) differ from the source", len(result.conflicts)
        )
    added = harvest_handybulk.update_master(result.parsed)
    if added:
        LOGGER.info(
            "Rate refresh: +%d row(s), source now current to %s", added, result.latest_date
        )

    # Route-level lanes, from a sibling page. Separate call because it is a
    # separate publication with its own failure mode: a class-average fetch
    # that works must not be held hostage to a lane page that does not, and
    # vice versa. This is what feeds opt.basis, and therefore the only reason
    # a quote from Indonesia prices differently from one from Australia.
    try:
        routes = harvest_route_rates.harvest()
        if routes.fetched and not routes.reason:
            added += harvest_route_rates.update_master(list(routes.quotes))
    except Exception:
        LOGGER.exception("Route-rate refresh failed; class averages are unaffected")

    # Port calls. A third source, and the one behind congestion, waiting times
    # and the tonnage field -- all of which were serving figures derived from
    # data that had gone stale because nothing ever re-ran the harvest. This is
    # the incremental path (`refresh_ports`), not the original full pull: each
    # port is asked only for rows newer than its own file already carries.
    if not PORT_REFRESH_DISABLED:
        try:
            from data_builders.harvest_portwatch import refresh_ports

            ports = refresh_ports()
            if ports.rows_added:
                LOGGER.info(
                    "Port refresh: +%d row(s) across %d port(s), now current to %s",
                    ports.rows_added,
                    ports.files_updated,
                    ports.newest_date,
                )
            if ports.failures:
                # Named, not counted: a partial refresh leaves some ports
                # current and others not, and "12 failed" does not tell anyone
                # which figures to distrust.
                LOGGER.warning(
                    "Port refresh: %d file(s) left unchanged: %s",
                    len(ports.failures),
                    ", ".join(ports.failures[:5]),
                )
        except Exception:
            LOGGER.exception("Port refresh failed; rate data is unaffected")

    return added


async def _rate_refresh_loop() -> None:
    """Keep the rate series current, and evaluate alerts when it moves.

    Runs once at startup so a desk that has been off for a week catches up on
    the first request rather than the next midnight, then on the interval.

    Evaluating alerts immediately after new data lands is the point of the
    whole arrangement: a watch on "Supramax falls below $20,000" is only
    meaningful if something notices when a new figure arrives. Without this the
    alert loop would still get there, but up to its own interval later, for no
    reason.
    """
    while True:
        try:
            added = await run_in_threadpool(_refresh_rates_once)
            if added and not ALERTS_DISABLED:
                fired = await run_in_threadpool(run_due_watches, _alert_store)
                if fired:
                    LOGGER.info("New rates fired %d watch(es)", len(fired))
        except asyncio.CancelledError:
            raise
        except Exception:
            LOGGER.exception("Rate refresh failed; the loop continues")
        await asyncio.sleep(RATE_REFRESH_SECONDS)


# ---------------------------------------------------------------------------
# Startup warmup
# ---------------------------------------------------------------------------
#
# Three caches in this system are expensive enough that paying them on a
# request is a visible failure rather than a slow response: the historical
# replay (~22 minutes), the tonnage field (~11s) and its validation ablation
# (~35s). Until now nothing warmed them, so the cost fell on whoever clicked
# first -- at a competition, a judge.
#
# The replay is now precomputed to disk by
# `data_builders.build_replay_snapshot` and merely LOADED here, which is why
# this is fast rather than a twenty-two minute startup. The tonnage caches are
# genuinely computed, in a background thread, so the server accepts
# connections immediately and the work overlaps the first few clicks instead
# of blocking them.
#
# Every step is individually guarded. A warmup is an optimisation; it must
# never be the reason the desk fails to start.

WARMUP_DISABLED: Final[bool] = os.environ.get("DESK_DISABLE_WARMUP", "").lower() in {
    "1",
    "true",
    "yes",
}


def _warm_caches() -> None:
    """Load the replay snapshot from disk and compute the cheap caches."""
    from opt.replay import snapshot_cache_path

    if snapshot_cache_path().exists():
        try:
            from opt.replay import get_replay_snapshot

            snap = get_replay_snapshot()
            LOGGER.info(
                "Warmup: replay snapshot ready (%d test rows, %.0fs of work loaded from disk)",
                snap.n_test_rows,
                snap.compute_seconds,
            )
        except Exception:
            LOGGER.exception("Warmup: replay snapshot failed to load; it will compute on demand")
    else:
        # Deliberately not computed here. Twenty-two minutes of PSO on startup
        # would be a worse failure than the one this fixes -- a server that
        # looks hung. Say what to run instead.
        LOGGER.warning(
            "Warmup: no stored replay snapshot for the current key. The Replay screen "
            "will take ~22 minutes on first use. Run "
            "`uv run python -m data_builders.build_replay_snapshot` before a demo."
        )

    for label, fn in (
        ("tonnage field", "get_snapshot"),
        ("tonnage ablation", "get_ablation_snapshot"),
    ):
        try:
            from tonnage import field as tonnage_field

            getattr(tonnage_field, fn)()
            LOGGER.info("Warmup: %s ready", label)
        except Exception:
            LOGGER.exception("Warmup: %s failed; it will compute on demand", label)

    # opt.repositioning's own docstring already names this cost ("order of
    # seconds, not milliseconds" of per-port file I/O) and caches it for the
    # process lifetime -- but nothing paid it here until now, so it fell on
    # whichever quote first included a vessel (the "Repositioning idle
    # vessels" stage), every single time the process had just (re)started.
    # On a host that restarts the process after an idle period, that is not
    # a rare cold-start tax, it's most requests.
    try:
        from opt.repositioning import warm_hazard_cache

        n = warm_hazard_cache()
        LOGGER.info("Warmup: repositioning hazard rates ready (%d port/class pairs)", n)
    except Exception:
        LOGGER.exception("Warmup: repositioning hazard rates failed; they will compute on demand")

@asynccontextmanager
async def _lifespan(_app: FastAPI) -> AsyncIterator[None]:
    # Done here rather than at import: uvicorn installs its handlers as part of
    # startup, so at import time there is nothing to attach to yet.
    _attach_to_uvicorn_logging()
    tasks: list[asyncio.Task] = []
    if not WARMUP_DISABLED:
        # In a worker thread, not on the event loop: this reads parquet files
        # and can run a real computation, and the server must be answering
        # requests while it happens rather than after.
        tasks.append(asyncio.create_task(run_in_threadpool(_warm_caches)))
    if not ALERTS_DISABLED:
        tasks.append(asyncio.create_task(_alert_loop()))
    if not RATE_REFRESH_DISABLED:
        tasks.append(asyncio.create_task(_rate_refresh_loop()))
    try:
        yield
    finally:
        for task in tasks:
            task.cancel()
        for task in tasks:
            with suppress(asyncio.CancelledError):
                await task


