@app.post("/backhaul")
def post_backhaul(req: BackhaulRequest) -> dict[str, Any]:
    """P6: backhaul opportunity score for one vessel against one or more
    candidate load ports after it discharges at `discharge_port`.
    Informational only, `credit_usd_per_mt` is always `null` today (see
    each result's `credit_evidence_reason`: FactPortCall carries no rate
    field to validate a $/MT credit against, structurally, not a sample-size
    gap). Never moves any recommendation this API makes elsewhere.

    Omitting `candidate_load_ports` sweeps every other real port, a real,
    measured multi-second operation (repeated berth_truth lookups per
    candidate), which is exactly why this is its own explicit endpoint and
    not folded into POST /quote.
    """
    discharge = _resolve_port(req.discharge_port, "discharge_port")
    # req.vessel is a required field (not Optional), so _resolve_vessels
    # always gets a real 1-element list back here -- no "vessel is None"
    # branch to guard, unlike QuoteRequest's genuinely-optional vessels.
    vessel = _resolve_vessels([req.vessel])[0]

    if req.candidate_load_ports is not None:
        candidates = [_resolve_port(p, "candidate_load_ports") for p in req.candidate_load_ports]
    else:
        candidates = [p for p in PortEnum if p is not discharge]

    # F-18: score_usd needs a real market rate to value cargo_probability
    # against -- today's real TC quote for this vessel's class, the same
    # class-level rate opt.repositioning's recommend_repositioning already
    # uses for the equivalent idle-vessel decision (see opt.backhaul's own
    # module docstring for the disclosed identical-everywhere limitation).
    # Missing for a real reason (no real quote at this date for this class)
    # is passed through as None, not fabricated -- backhaul_opportunity_score
    # then leaves score_usd None too and says why in `limitations`.
    _, quotes = forecast_all_classes(latest_available_date())
    base_tce = quotes.get(vessel.vessel_class)

    results = [
        backhaul_opportunity_score(
            vessel, discharge, port,
            assumed_window_days=req.assumed_window_days, base_tce_usd_per_day=base_tce,
        )
        for port in candidates
    ]
    results.sort(key=lambda r: r.score_usd if r.score_usd is not None else r.score, reverse=True)
    return {
        "vessel_id": vessel.vessel_id,
        "discharge_port": discharge.name,
        "results": [_backhaul_score_to_json(r) for r in results],
    }


@app.post("/portfolio")
def post_portfolio(req: PortfolioRequest) -> dict[str, Any]:
    """F-16: the PS's own stated objective, given a real endpoint,
    ``opt.portfolio.optimize_portfolio_mix``/``efficient_frontier`` (real,
    already tested logic that previously had no way to be called from the
    running product at all). Returns one `recommended` mix at the caller's
    own `risk_aversion_k`, plus an 8-point `frontier` spanning 0 (pure
    cost-minimization) to 8 real spot-cost standard deviations of risk
    aversion, always both, so a screen can show a single answer and the
    cost/risk tradeoff behind it in one round trip.

    Deliberately standalone, not part of POST /quote's automatic pipeline,
    see PortfolioRequest's own docstring for why (three real business inputs
    this system cannot infer).
    """
    vessel_class = _resolve_vessel_class(req.vessel_class, "vessel_class")
    resolved_as_of = req.as_of if req.as_of is not None else latest_available_date()
    fans_by_class, quotes = forecast_all_classes(resolved_as_of)

    if vessel_class not in quotes or not fans_by_class.get(vessel_class):
        raise HTTPException(
            status_code=503,
            detail=(
                f"No real TC quote/forecast for {vessel_class.value} as of {resolved_as_of}, "
                "cannot build a portfolio mix. Try a different as_of date."
            ),
        )
    today_quote = quotes[vessel_class]
    forecasts = fans_by_class[vessel_class]

    basis_entry = None
    route_basis_applied = False
    if req.origin_port is not None and req.dest_port is not None:
        origin = _resolve_port(req.origin_port, "origin_port")
        _resolve_port(req.dest_port, "dest_port")  # validated, not otherwise used -- basis keys off origin's route family only, same as opt.quote
        route_family = route_family_for_origin(origin)
        entries = basis_table_to_entries(_cached_route_basis_table())
        basis_entry = entries.get(route_family)
        route_basis_applied = basis_entry is not None

    try:
        spot_cost, spot_std = spot_cost_stats(forecasts, vessel_class, req.contract_term_days, basis_entry)

        def _mix_kwargs(risk_aversion: float) -> dict[str, Any]:
            return {
                "today_quote_usd_per_day": today_quote, "forecasts": forecasts, "vessel_class": vessel_class,
                "contract_term_days": req.contract_term_days, "plant_burden_cover_days": req.plant_burden_cover_days,
                "stockout_cost_usd": req.stockout_cost_usd,
                "spot_sourcing_hazard_rate_per_day": req.spot_sourcing_hazard_rate_per_day,
                "risk_aversion": risk_aversion, "basis": basis_entry,
            }

        recommended_ra = req.risk_aversion_k / spot_std if spot_std > 0 else 0.0
        recommended = optimize_portfolio_mix(**_mix_kwargs(recommended_ra))

        frontier_ras = [k / spot_std if spot_std > 0 else 0.0 for k in _PORTFOLIO_FRONTIER_K]
        frontier = efficient_frontier(
            today_quote_usd_per_day=today_quote, forecasts=forecasts, vessel_class=vessel_class,
            contract_term_days=req.contract_term_days, plant_burden_cover_days=req.plant_burden_cover_days,
            stockout_cost_usd=req.stockout_cost_usd,
            spot_sourcing_hazard_rate_per_day=req.spot_sourcing_hazard_rate_per_day,
            risk_aversion_grid=tuple(frontier_ras), basis=basis_entry,
        )
    except ValueError as exc:
        raise HTTPException(status_code=422, detail=str(exc)) from exc

    return {
        "vessel_class": vessel_class.value,
        "as_of": resolved_as_of.isoformat(),
        "contract_term_days": req.contract_term_days,
        "today_quote_usd_per_day": today_quote,
        "spot_cost_usd": spot_cost,
        "spot_cost_std_usd": spot_std,
        "route_basis_applied": route_basis_applied,
        "recommended": _portfolio_mix_to_json(recommended, risk_aversion_k=req.risk_aversion_k, risk_aversion=recommended_ra),
        "frontier": [
            _portfolio_mix_to_json(m, risk_aversion_k=k, risk_aversion=ra)
            for m, k, ra in zip(frontier, _PORTFOLIO_FRONTIER_K, frontier_ras)
        ],
    }


