    return {
        "origin_port": origin.name,
        "dest_port": dest.name,
        "as_of": resolved_as_of.isoformat(),
        "chokepoints": [model_to_json(c) for c in chokepoints],
        "jwc_listed_areas": list(listed_areas),
        "transit_days": transit_days,
        "war_risk_premium": premium,
    }


